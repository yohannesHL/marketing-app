import { expect, test } from "@playwright/test";

test("customer connects and selects their verified YouTube channel independently of advertising", async ({ page }, info) => {
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/sign-in?returnTo=%2Fconnections");
  await page.getByLabel(/^Email/).fill(`youtube-${info.project.name}@example.test`);
  await page.getByLabel(/^Password/).fill("isolated-test-password-for-fixtures");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/connections$/);
  const social = page.getByTestId("social-connections");
  const callback = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/connections/youtube/callback");
  await social.getByRole("button", { name: "Connect YouTube Shorts", exact: true }).click();
  expect((await callback).status()).toBe(303);
  await expect(page).toHaveURL(/\/connections\?provider=youtube&result=connected/);
  const card = social.getByTestId("provider-connection").filter({ has: page.getByRole("heading", { name: "YouTube publishing", exact: true }) });
  await expect(card).toContainText("Mockoon test connection");
  const destination = card.getByTestId("connection-destination");
  await expect(destination).toHaveCount(1);
  await expect(destination).toContainText("UCfixtureBrandA");
  await expect(destination.getByRole("combobox")).toHaveCount(0);
  const selectRequest = page.waitForRequest((r) => /\/api\/connections\/youtube\/[^/]+\/select$/.test(new URL(r.url()).pathname));
  await destination.getByRole("button", { name: "Select account", exact: true }).click();
  expect(Object.keys((await selectRequest).postDataJSON())).toEqual(["destinationId"]);
  await expect(destination).toContainText("Selected");
  const rows = await (await page.request.get("/api/connections")).json();
  expect(rows).toHaveLength(1); expect(rows[0]).toMatchObject({ provider: "GOOGLE", capability: "SOCIAL", connectionMode: "MOCK" });
  expect(rows[0].destinations[0].selected).toBe(true);
  expect(JSON.stringify(rows)).not.toMatch(/yt-access|yt-refresh|Ciphertext|fixture-yt-secret/);
  await expect(page.getByTestId("paid-connections").getByTestId("provider-connection")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Check selected accounts", exact: true })).toBeDisabled();
  await expect(page.getByRole("status")).toContainText("Publishing destination selected");
  await card.getByRole("button", { name: "Refresh accounts", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Accounts refreshed");
  await destination.getByRole("button", { name: "Deselect account", exact: true }).click();
  await expect(destination.getByRole("button", { name: "Select account", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("youtube-connections-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("youtube-connections-desktop.png"), fullPage: true });
  await card.getByRole("button", { name: "Disconnect YouTube publishing", exact: true }).click();
  await card.getByRole("button", { name: "Confirm disconnect", exact: true }).click();
  await expect(card).toContainText("Disconnected");
});
