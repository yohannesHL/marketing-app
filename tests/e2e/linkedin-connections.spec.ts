import { expect, test } from "@playwright/test";

test("LinkedIn connects distinct member and organization authors with explicit visibility and no advertising action", async ({ page }, info) => {
  test.setTimeout(120_000);
  const writes: string[] = [];
  page.on("request", request => {
    if (request.method() === "POST" && (/\/enqueue$/.test(new URL(request.url()).pathname) || new URL(request.url()).pathname.startsWith("/api/ads/"))) writes.push(request.url());
  });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/sign-in?returnTo=%2Fconnections");
  await page.getByLabel(/^Email/).fill(`linkedin-${info.project.name}@example.test`);
  await page.getByLabel(/^Password/).fill("isolated-test-password-for-fixtures");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/connections$/);
  const social = page.getByTestId("social-connections");
  const callback = page.waitForResponse(response => new URL(response.url()).pathname === "/api/connections/linkedin/callback");
  await social.getByRole("button", { name: "Connect LinkedIn", exact: true }).click();
  expect((await callback).status()).toBe(303);
  await expect(page).toHaveURL(/\/connections\?provider=linkedin&result=connected/);
  const card = social.getByTestId("provider-connection");
  const member = card.getByTestId("connection-destination").filter({ has: page.getByRole("heading", { name: "Synthetic member", exact: true }) });
  const organization = card.getByTestId("connection-destination").filter({ has: page.getByRole("heading", { name: "LinkedIn organization 123", exact: true }) });
  await expect(member).toHaveCount(1); await expect(organization).toHaveCount(1);
  await member.getByRole("button", { name: "Select account", exact: true }).click();
  await expect(member.getByRole("button", { name: "Deselect account", exact: true })).toBeVisible();
  await organization.getByRole("button", { name: "Select account", exact: true }).click();
  await expect(organization.getByRole("button", { name: "Deselect account", exact: true })).toBeVisible();
  const rows = await (await page.request.get("/api/connections")).json(); expect(rows).toHaveLength(1);
  expect(rows[0]).toMatchObject({ provider: "LINKEDIN", providerUserId: "member-a", capability: "SOCIAL", connectionMode: "MOCK" });
  expect(rows[0].destinations.map((d: {kind: string; selected: boolean}) => [d.kind, d.selected]).sort()).toEqual([["LINKEDIN_MEMBER", true], ["LINKEDIN_ORGANIZATION", true]]);
  expect(JSON.stringify(rows)).not.toMatch(/org-token|fixture-li-secret|Ciphertext|refreshExpiresAt|accessToken/);
  await expect(page.getByTestId("paid-connections").getByTestId("provider-connection")).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("linkedin-authors-mobile.png"), fullPage: true });
  await page.goto("/social/create");
  await page.getByLabel(/^Draft title/).fill("LinkedIn member and organization review");
  await page.getByLabel("Caption or post text", { exact: true }).fill("Customer-reviewed LinkedIn draft.");
  await page.getByRole("checkbox", { name: /^Synthetic member\b/ }).check();
  await page.getByRole("checkbox", { name: /^LinkedIn organization 123\b/ }).check();
  const visibility = page.getByLabel("LinkedIn visibility", { exact: true }); await expect(visibility).toHaveCount(2);
  await expect(visibility.nth(0)).toHaveValue(""); await expect(visibility.nth(1)).toHaveValue("");
  await expect(visibility.nth(0).locator("option")).toHaveText(["Choose visibility", "Public", "Connections"]);
  await expect(visibility.nth(1).locator("option")).toHaveText(["Choose visibility", "Public"]);
  await visibility.nth(0).selectOption("CONNECTIONS"); await visibility.nth(1).selectOption("PUBLIC");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: info.outputPath("linkedin-review-desktop.png"), fullPage: true });
  const saved = page.waitForResponse(response => new URL(response.url()).pathname === "/api/social/posts" && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  const response = await saved; expect(response.status()).toBe(201); const post = await response.json();
  expect(post.publishingEnabled).toBe(false); expect(post.deliveries).toEqual([]); expect(writes).toEqual([]);
  expect(post.revision.variants).toHaveLength(2);
  const memberId = rows[0].destinations.find((d: {kind: string}) => d.kind === "LINKEDIN_MEMBER").id;
  const orgId = rows[0].destinations.find((d: {kind: string}) => d.kind === "LINKEDIN_ORGANIZATION").id;
  expect(post.revision.variants.find((v: {destinationId: string}) => v.destinationId === memberId)).toMatchObject({ format: "TEXT", providerOptions: { visibility: "CONNECTIONS" } });
  expect(post.revision.variants.find((v: {destinationId: string}) => v.destinationId === orgId)).toMatchObject({ format: "TEXT", providerOptions: { visibility: "PUBLIC" } });
  expect(JSON.stringify(post)).not.toMatch(/org-token|fixture-li-secret|Ciphertext|accessToken/);
});
