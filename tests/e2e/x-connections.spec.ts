import { expect, test } from "@playwright/test";

test("X requires explicit API allowances and quotes the current owned draft without publishing", async ({ page }, info) => {
  test.setTimeout(120_000);
  const writes: string[] = [];
  page.on("request", (request) => { const path = new URL(request.url()).pathname;
    if (request.method() === "POST" && (path.endsWith("/enqueue") || path.startsWith("/api/ads/"))) writes.push(path); });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/sign-in?returnTo=%2Fconnections");
  await page.getByLabel(/^Email/).fill(`x-${info.project.name}@example.test`);
  await page.getByLabel(/^Password/).fill("isolated-test-password-for-fixtures");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/connections$/);
  const social = page.getByTestId("social-connections"), connect = social.getByRole("button", { name: "Connect X", exact: true });
  const limit = page.getByLabel("Maximum X connection API cost (USD)", { exact: true });
  await expect(limit).toHaveValue(""); await expect(connect).toBeDisabled();
  await limit.fill("0.0000001"); await expect(connect).toBeDisabled();
  await limit.fill("9007199254.740992"); await expect(connect).toBeDisabled();
  await limit.fill("0.05");
  const started = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/connections/x/start");
  const callback = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/connections/x/callback");
  await connect.click(); const start = await started;
  expect(start.status()).toBe(200); expect(start.request().postDataJSON()).toEqual({ maxApiCostMicros: 50_000 });
  expect((await callback).status()).toBe(303);
  await expect(page).toHaveURL(/\/connections\?provider=x&result=connected/);
  const card = social.getByTestId("provider-connection"), actionLimit = card.getByLabel("Maximum X API cost for this action (USD)", { exact: true });
  await expect(card.getByRole("heading", { name: /^Fixture X user\b/ })).toBeVisible();
  await expect(actionLimit).toHaveValue(""); await expect(card.getByRole("button", { name: "Check read access", exact: true })).toBeDisabled();
  await expect(card.getByRole("button", { name: "Refresh accounts", exact: true })).toBeDisabled();
  const selected = page.waitForResponse((response) => new URL(response.url()).pathname.endsWith("/select"));
  await card.getByRole("button", { name: "Select account", exact: true }).click();
  const selection = await selected; expect(selection.status()).toBe(200);
  expect(Object.keys(selection.request().postDataJSON())).toEqual(["destinationId"]);
  await expect(page.getByText("Cached verified X identity selected without a new provider request or API allocation.", { exact: false })).toBeVisible();
  const rows = await (await page.request.get("/api/connections")).json(), connection = rows[0], destination = connection.destinations[0];
  expect(connection).toMatchObject({ provider: "X", providerUserId: "1001", capability: "SOCIAL", connectionMode: "MOCK" });
  expect(destination).toMatchObject({ kind: "X_PROFILE", externalId: "1001", selected: true });
  expect(JSON.stringify(rows)).not.toMatch(/fixture-x-secret|accessToken|Ciphertext|refreshExpiresAt/);
  await actionLimit.fill("0.05");
  const checked = page.waitForResponse((response) => new URL(response.url()).pathname.endsWith("/check"));
  await card.getByRole("button", { name: "Check read access", exact: true }).click();
  const check = await checked; expect(check.status()).toBe(200);
  expect(check.request().postDataJSON()).toEqual({ destinationId: destination.id, maxApiCostMicros: 50_000 });
  await expect(actionLimit).toHaveValue("");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("x-connection-mobile.png"), fullPage: true });
  await page.goto("/social/create");
  await page.getByLabel(/^Draft title/).fill("X reviewed allocation draft");
  await page.getByLabel("Caption or post text", { exact: true }).fill("漢".repeat(140));
  await page.getByRole("checkbox", { name: /^Fixture X user\b/ }).check();
  const estimate = page.getByTestId("x-local-estimate");
  await expect(estimate.getByText("280 / 280 weighted characters.", { exact: true })).toBeVisible();
  await expect(estimate.getByText("Synthetic Mockoon fixture rates; no real API charges.", { exact: true })).toBeVisible();
  await expect(estimate.getByText("Actual bill: unavailable. Provider credit balance: unavailable.", { exact: true })).toBeVisible();
  const cost = page.getByLabel("Maximum X publishing API cost (USD)", { exact: true }); await expect(cost).toHaveValue("");
  const ai = page.getByLabel("This X post was made with AI", { exact: true }), partnership = page.getByLabel("This X post is a paid partnership", { exact: true });
  await expect(ai).toHaveValue(""); await expect(partnership).toHaveValue("");
  // Delay an actual local quote request, then let the newer content's real
  // response win. No provider or application JSON response is fabricated.
  let releaseOld: (() => void) | undefined, startedOld: (() => void) | undefined;
  const oldStarted = new Promise<void>((resolve) => { startedOld = resolve; });
  await page.route((url) => url.pathname === "/api/social/x/quote", async (route) => {
    if (route.request().postDataJSON().body === "Old quote must not win.") { startedOld!(); await new Promise<void>((resolve) => { releaseOld = resolve; }); }
    await route.continue();
  });
  const caption = page.getByLabel(/^Caption for Fixture X user\b/);
  await caption.fill("Old quote must not win."); await oldStarted;
  const urlQuote = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/social/x/quote" && response.request().postDataJSON().body === "https://example.com/a-long-url");
  await caption.fill("https://example.com/a-long-url");
  const quoted = await urlQuote; expect(quoted.status()).toBe(200);
  const quote = await quoted.json(); expect(quote).toMatchObject({ kind: "ESTIMATED_API_ALLOCATION", mode: "mock", weightedLength: 23, includesUrl: true, actualBill: null, providerCreditBalance: null });
  expect(quoted.request().postDataJSON()).toEqual({ destinationId: destination.id, body: "https://example.com/a-long-url", format: "TEXT", mediaIds: [] });
  const late = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/social/x/quote" && response.request().postDataJSON().body === "Old quote must not win.");
  releaseOld!(); expect((await late).status()).toBe(200);
  await expect(estimate.getByText("23 / 280 weighted characters.", { exact: true })).toBeVisible();
  await expect(estimate.getByText("This post contains a URL; the configured URL-post rate applies.", { exact: true })).toBeVisible();
  await cost.fill("1"); await ai.selectOption("no"); await partnership.selectOption("no");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("x-review-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("x-review-desktop.png"), fullPage: true });
  const saved = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/social/posts" && response.request().method() === "POST");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  const response = await saved; expect(response.status()).toBe(201); const post = await response.json();
  expect(post.publishingEnabled).toBe(false); expect(post.deliveries).toEqual([]); expect(writes).toEqual([]);
  expect(post.revision.variants[0]).toMatchObject({ destinationId: destination.id, format: "TEXT", body: "https://example.com/a-long-url", providerOptions: { madeWithAi: false, paidPartnership: false, maxApiCostMicros: 1_000_000 } });
  expect(JSON.stringify(post)).not.toMatch(/fixture-x-secret|accessToken|Ciphertext/);
});
